PRICE_RE = re.compile(r'\d')
ARABIC = re.compile(r'[؀-ۿ]')


def extra_classes(node, base):
    """The widget's classes beyond the builder's own: motion and stage hooks."""
    return ' '.join(c for c in node.cls if c not in base)


def widget_of(w):
    """One `bpr-widget` → a template with no words in it, or None."""
    cls = ' '.join(w.cls)
    style = style_obj(w.a.get('style'))
    kind = next((c[len('bpr-widget--'):] for c in w.cls if c.startswith('bpr-widget--')), '')
    base = {'cls': cls}
    if style:
        base['style'] = style
    kids = w.kids()

    if kind == 'heading':
        h = kids[0]
        txt = h.text().strip()
        if h.tag == 'h1':
            slot = 'headline'
        elif h.tag == 'h6':
            slot = 'kicker'
        elif h.tag in ('h3', 'h4') and PRICE_RE.search(txt) and len(txt) < 24:
            slot = 'price'
        else:
            slot = 'title'
        return {**base, 'k': 'heading', 'tag': h.tag, 'hcls': ' '.join(h.cls), 'hstyle': style_obj(h.a.get('style')), 'slot': slot}

    if kind == 'text':
        t = kids[0]
        return {**base, 'k': 'text', 'tcls': ' '.join(t.cls), 'tstyle': style_obj(t.a.get('style'))}

    if kind == 'button':
        b = kids[0]
        a = b.find(lambda n: n.tag == 'a')
        return {**base, 'k': 'button', 'bcls': ' '.join(b.cls), 'acls': ' '.join(a.cls), 'astyle': style_obj(a.a.get('style'))}

    if kind == 'image':
        img = w.find(lambda n: n.tag == 'img')
        return {**base, 'k': 'image', 'istyle': style_obj(img.a.get('style'))}

    if kind == 'checklist':
        ul = kids[0]
        li = ul.kids()[0]
        mark = li.kids()[0]
        return {
            **base, 'k': 'checklist', 'ulStyle': style_obj(ul.a.get('style')),
            'liStyle': style_obj(li.a.get('style')), 'markStyle': style_obj(mark.a.get('style')),
            'mark': mark.text().strip(),
        }

    if kind == 'features':
        g = kids[0]
        items = g.kids()
        first = items[0]
        icon, body = first.kids()[0], first.kids()[1]
        strong = body.find(lambda n: n.tag == 'strong')
        span = body.find(lambda n: n.tag == 'span')
        numbered = any(it.kids()[0].find(lambda n: n.tag == 'i') is not None for it in items)
        icons = [] if numbered else [it.kids()[0].text().strip() for it in items]
        return {
            **base, 'k': 'features', 'gcls': ' '.join(g.cls), 'gstyle': style_obj(g.a.get('style')),
            'item': style_obj(first.a.get('style')), 'icon': style_obj(icon.a.get('style')),
            'strong': style_obj(strong.a.get('style')) if strong is not None else {},
            'span': style_obj(span.a.get('style')) if span is not None else {},
            'numbered': numbered, 'icons': icons,
        }

    if kind == 'faq':
        acc = kids[0]
        item = acc.kids()[0]
        btn = item.find(lambda n: n.tag == 'button')
        plus = btn.find(lambda n: n.tag == 'span')
        ans = [k for k in item.kids() if k.tag == 'div'][0]
        ast = style_obj(ans.a.get('style'))
        ast.pop('display', None)  # their closed state; ours is <details>
        return {
            **base, 'k': 'faq', 'item': style_obj(item.a.get('style')), 'button': style_obj(btn.a.get('style')),
            'plus': style_obj(plus.a.get('style')) if plus is not None else {},
            'plusText': plus.text().strip() if plus is not None else '+', 'answer': ast,
        }

    if kind == 'ctabanner':
        box = kids[0]
        box_style = style_obj(box.a.get('style'))
        # Their banner over THEIR product's photo: the photo goes (style_obj
        # drops it), and the renderer puts OUR product's picture in its place.
        photo = bool(FOREIGN_URL.search(box.a.get('style') or ''))
        overlay = box.find(lambda n: n.tag == 'span')
        inner = [k for k in box.kids() if k.tag == 'div'][0]
        h2 = inner.find(lambda n: n.tag in ('h2', 'h3'))
        p = inner.find(lambda n: n.tag == 'p')
        a = inner.find(lambda n: n.tag == 'a')
        return {
            **base, 'k': 'cta', 'boxCls': ' '.join(box.cls), 'box': box_style, 'photo': photo,
            'overlay': style_obj(overlay.a.get('style')) if overlay is not None else {},
            'inner': style_obj(inner.a.get('style')),
            'h': style_obj(h2.a.get('style')) if h2 is not None else {}, 'htag': h2.tag if h2 is not None else 'h2',
            'p': style_obj(p.a.get('style')) if p is not None else {},
            'a': style_obj(a.a.get('style')) if a is not None else {},
        }

    if kind == 'html':
        return html_widget(base, w)

    return None


SAFE_ATTRS = {'class', 'style', 'aria-hidden', 'data-imx', 'data-mode', 'data-fz', 'role', 'type', 'viewBox', 'viewbox',
              'preserveAspectRatio', 'preserveaspectratio', 'd', 'fill', 'stroke', 'stroke-width', 'stroke-linecap',
              'stroke-linejoin', 'opacity', 'cx', 'cy', 'r', 'x', 'y', 'width', 'height', 'xmlns', 'pathLength',
              'pathlength', 'vector-effect', 'data-mx-scrub', 'data-mx-pin', 'tabindex'}
SVG_CASE = {'viewbox': 'viewBox', 'preserveaspectratio': 'preserveAspectRatio', 'pathlength': 'pathLength'}


def deco(node):
    """A decorative node (no words) → a tiny tree our renderer can draw."""
    if isinstance(node, str):
        return None
    attrs = {}
    for k, v in node.a.items():
        if k not in SAFE_ATTRS or v is None:
            continue
        if k == 'class':
            attrs['className'] = v
        elif k == 'style':
            attrs['style'] = style_obj(v)
        elif k.startswith(('aria-', 'data-')):
            attrs[k] = v
        elif k == 'tabindex':
            attrs['tabIndex'] = v
        else:
            attrs[SVG_CASE.get(k, camel(k))] = v
    kids = [d for d in (deco(c) for c in node.c) if d]
    out = {'t': node.tag}
    if attrs:
        out['a'] = attrs
    if kids:
        out['c'] = kids
    return out


def html_widget(base, w):
    parts = []
    for n in w.kids():
        if n.tag in ('style', 'script'):
            continue
        if 'mx-marquee' in n.cls:
            track = n.find(lambda x: 'mx-marquee-track' in x.cls)
            row = track.kids()[0]
            sep = row.find(lambda x: x.tag == 'i')
            parts.append({'m': 'marquee', 'cls': ' '.join(n.cls), 'style': style_obj(n.a.get('style')),
                          'sep': sep.text().strip() if sep is not None else '✦'})
        elif 'mx-topbar' in n.cls:
            parts.append({'m': 'topbar', 'cls': ' '.join(n.cls), 'style': style_obj(n.a.get('style'))})
        elif not ARABIC.search(n.text()) and not re.search(r'[A-Za-z]{3,}', n.text()):
            parts.append({'m': 'deco', 'node': deco(n)})
        else:
            # A kit section that carries words (cascade, road, facts, story,
            # coverflow…). Its words are theirs and stay behind; its shape is
            # the kit stylesheet's, so the renderer redraws the ones that have
            # a block of ours to fill them (cascade · road · facts) from the
            # same classes, with the root's own colour variables.
            kind = next((c[len('mx-'):] for c in n.cls if c.startswith('mx-')), '')
            parts.append({'m': 'kit', 'kind': kind, 'cls': ' '.join(n.cls), 'style': style_obj(n.a.get('style'))})
    return {**base, 'k': 'html', 'parts': parts}


def classify(sec, widgets, first):
    kinds = [w['k'] for w in widgets]
    slots = [w.get('slot') for w in widgets if w['k'] == 'heading']
    html_parts = [p for w in widgets if w['k'] == 'html' for p in w['parts']]
    if any(p['m'] == 'marquee' for p in html_parts):
        return 'marquee'
    if any(p['m'] == 'topbar' for p in html_parts) and 'heading' not in kinds:
        return 'topbar'
    if any(p['m'] == 'kit' for p in html_parts):
        return 'kit'
    if 'headline' in slots:
        return 'hero'
    if 'faq' in kinds:
        return 'faq'
    if 'cta' in kinds:
        return 'topbanner' if first else 'cta'
    if kinds == ['text']:
        return 'announce'
    if kinds == ['image']:
        return 'image'
    if kinds == ['features']:
        return 'trust'
    if 'features' in kinds:
        feat = next(w for w in widgets if w['k'] == 'features')
        return 'steps' if feat['numbered'] else 'features'
    if 'checklist' in kinds:
        return 'why'
    if 'image' in kinds and 'text' in kinds and 'title' in slots:
        return 'zig'
    if 'text' in kinds and 'title' in slots:
        return 'statement'
    return 'other'


def sections_of(body_html):
    root = parse(body_html)
    out = []
    secs = []

    def collect(n):
        for c in n.kids():
            if c.tag == 'section' and 'bpr-section' in c.cls:
                secs.append(c)
            else:
                collect(c)

    collect(root)
    for i, s in enumerate(secs):
        container = None
        rows_parent = s
        cont = next((k for k in s.kids() if 'container' in k.cls), None)
        if cont is not None:
            container = style_obj(cont.a.get('style'))
            rows_parent = cont
        rows = []
        all_widgets = []
        for r in rows_parent.kids():
            if 'bpr-row' not in r.cls:
                continue
            cols = []
            for c in r.kids():
                if 'bpr-col' not in c.cls:
                    continue
                ws = []
                for w in c.kids():
                    if 'bpr-widget' not in w.cls:
                        continue
                    t = widget_of(w)
                    if t:
                        ws.append(t)
                cols.append({'cls': ' '.join(c.cls), 'widgets': ws})
                all_widgets.extend(ws)
            rows.append({'cls': ' '.join(r.cls), 'cols': cols})
        role = classify(s, all_widgets, i == 0)
        out.append({'role': role, 'cls': ' '.join(s.cls), 'container': container, 'rows': rows})
    return out


def styles_in(html):
    return [m.group(2) for m in re.finditer(r'<style( id="[^"]*")?>(.*?)</style>', html, re.S)]


def read_design(did, html):
    body_start = html.find('<body')
    order_at = html.find('id="order-section"')
    order_at = html.rfind('<section', 0, order_at)
    head, body = html[:body_start], html[body_start:order_at]

    shell = next(s for s in styles_in(head) if ':root' in s[:400])
    var = lambda name: (re.search(r'--' + name + r':\s*([^;]+);', shell) or [None, ''])[1].strip()
    page_bg = re.search(r'body\s*\{[^}]*background:\s*([^;]+);', shell).group(1).strip()
    family = var('font-family').strip("'\"")
    google = None
    for m in re.finditer(r'[?&]family=([^"&]+)', head):
        spec = m.group(1)
        if spec.split(':')[0].replace('+', ' ') == family:
            google = spec
    custom = next((m.group(1) for m in re.finditer(r'<style id="lp-custom-css">(.*?)</style>', head, re.S)), '')

    # The layout stylesheet(s) inside the body: the builder's per-section
    # rules, and for an animated design its effect and its kit.
    layout_css, fx_css, kit = [], [], False
    for s in styles_in(body):
        if '.mx-progress' in s and '.mx-marquee' in s:
            kit = True  # the shared kit — written once, in imx-kit.ts
        elif '.imx-fx' in s and '.bpr-row' not in s[:200]:
            fx_css.append(s)
        else:
            layout_css.append(s)

    clean_body = re.sub(r'<script.*?</script>', '', body, flags=re.S)
    clean_body = re.sub(r'<style.*?</style>', '', clean_body, flags=re.S)
    sections = sections_of(clean_body)

    def custom_keep(sel):
        # Only the parts of their override that paint something WE draw: the
        # order section's backdrop, the top bar, its brand. Never their form
        # card's insides, and never `.order-section p` — that would recolour
        # our form's own words.
        return sel in ('.zd-order-section', '.zd-navbar', '.zd-navbar .zd-brand-name')

    order_bg = None
    m = re.search(r'\.order-section\{background:([^}!]+)', custom)
    if m:
        order_bg = m.group(1).strip()

    return {
        'id': did,
        'animated': did.startswith('imx-'),
        'kit': kit,
        'reveal': any('bpr-anim' in w['cls'] for sec in sections for r in sec['rows'] for c in r['cols'] for w in c['widgets']),
        'font': {'family': family, 'google': google},
        'vars': {
            'primary': var('primary'), 'btn': var('btn-brand-color'), 'orderHeader': var('order-header-color'),
            'ink': var('font-color'), 'pageBg': page_bg,
        },
        'orderBg': order_bg,
        'css': ''.join(rescope(c) for c in layout_css) + ''.join(rescope(c) for c in fx_css) + rescope(custom, custom_keep),
        'sections': sections,
    }


