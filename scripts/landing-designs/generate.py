def strip_comments(css):
    return re.sub(r'/\*.*?\*/', '', css, flags=re.S)


RENAME = {
    # Their page chrome, renamed so it cannot collide with OUR classes —
    # `.lp-footer` is our footer block's own class.
    'lp-navbar': 'zd-navbar',
    'lp-footer': 'zd-footer',
    'btn-brand': 'zd-btn-brand',
    'brand-name': 'zd-brand-name',
    'order-section': 'zd-order-section',
}


def rename_classes(sel):
    for a, b in RENAME.items():
        sel = re.sub(r'\.' + re.escape(a) + r'(?![\w-])', '.' + b, sel)
    return sel


DOC_CLASSES = ('.mx-js', '.bpr-js', '.mx-film', '.mx-cursor-on', '.mx-cursor-hot')


def scope_one(sel):
    sel = sel.strip()
    if not sel:
        return sel
    if sel in ('html', 'body', ':root'):
        return SCOPE
    # `html[data-motion="none"] .x`, `html.mx-film .x`, `.mx-js .x`,
    # `[dir=rtl].mx-js .x` — the document-level part stays where it is (their
    # scripts set it on <html>), and the scope goes in right after it.
    m = re.match(r'^((?:html)?(?:\[[^\]]+\]|\.[\w-]+)*)(\s+|$)(.*)$', sel)
    if m:
        head, rest = m.group(1), m.group(3)
        doc = head.startswith('html') or any(head.startswith(c) or c in head for c in DOC_CLASSES)
        if head.startswith('[dir=rtl]') and not any(c in head for c in DOC_CLASSES):
            # The page's direction is on our root, not on <html>.
            return SCOPE + '[dir=rtl] ' + rest if rest else SCOPE + '[dir=rtl]'
        if doc:
            dirpart = ''
            if '[dir=rtl]' in head:
                head = head.replace('[dir=rtl]', '')
                dirpart = '[dir=rtl]'
            if head in ('html', ''):
                head = 'html'
            return (head + ' ' + SCOPE + dirpart + (' ' + rest if rest else '')).strip()
    return SCOPE + ' ' + sel


def rescope(css, keep=None):
    """Prefix every selector with the scope; recurse into @media/@supports."""
    css = strip_comments(css)
    out = []
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        sel = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{':
                depth += 1
            elif css[k] == '}':
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if sel.startswith('@'):
            if sel.startswith(('@media', '@supports')):
                inner = rescope(body, keep)
                if inner:
                    out.append(sel + '{' + inner + '}')
            elif sel.startswith('@keyframes') or sel.startswith('@-webkit-keyframes'):
                out.append(sel + '{' + re.sub(r'\s+', ' ', body.strip()) + '}')
            # anything else (@import, @font-face) is dropped: no outside hosts
        else:
            sels = [rename_classes(s) for s in split_top(sel, ',')]
            if keep is not None:
                sels = [s for s in sels if keep(s.strip())]
            if sels:
                decl = re.sub(r'\s+', ' ', body.strip())
                out.append(','.join(scope_one(s) for s in sels) + '{' + decl + '}')
        i = k
    return ''.join(out)


