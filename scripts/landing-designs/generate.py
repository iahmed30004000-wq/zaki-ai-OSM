def split_top(s, sep):
    """Split on `sep` outside parentheses and quotes."""
    out, depth, cur, q = [], 0, '', None
    for ch in s:
        if q:
            cur += ch
            if ch == q:
                q = None
            continue
        if ch in '"\'':
            q = ch
        elif ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return out


def camel(prop):
    if prop.startswith('--'):
        return prop
    if prop.startswith('-webkit-'):
        prop = 'Webkit-' + prop[len('-webkit-'):]
    parts = prop.split('-')
    return parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


FOREIGN_URL = re.compile('url\\(\\s*(?![\'"]?(?:data:|#))')


def style_obj(s):
    """An inline style as a React object. A `url()` to anything but an inline
    picture is dropped: their files (the product photo) are theirs."""
    out = {}
    for decl in split_top(s or '', ';'):
        if ':' not in decl:
            continue
        k, v = decl.split(':', 1)
        k, v = k.strip(), v.strip()
        if not k or not v:
            continue
        if FOREIGN_URL.search(v):
            continue
        out[camel(k.lower() if not k.startswith('--') else k)] = v
    return out


