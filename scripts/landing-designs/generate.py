VOID = {'img', 'br', 'input', 'meta', 'link', 'hr', 'source', 'path', 'circle', 'rect', 'stop', 'line', 'ellipse', 'polygon', 'polyline'}


class Node:
    def __init__(self, tag, attrs):
        self.tag = tag
        self.a = dict(attrs)
        self.c = []

    @property
    def cls(self):
        return (self.a.get('class') or '').split()

    def text(self):
        out = []
        for c in self.c:
            out.append(c if isinstance(c, str) else c.text())
        return ''.join(out)

    def kids(self):
        return [c for c in self.c if isinstance(c, Node)]

    def find(self, pred):
        for c in self.kids():
            if pred(c):
                return c
            r = c.find(pred)
            if r is not None:
                return r
        return None


class Parser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node('root', [])
        self.stack = [self.root]

    def handle_starttag(self, tag, attrs):
        n = Node(tag, attrs)
        self.stack[-1].c.append(n)
        if tag not in VOID:
            self.stack.append(n)

    def handle_startendtag(self, tag, attrs):
        self.stack[-1].c.append(Node(tag, attrs))

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag == tag:
                del self.stack[i:]
                return

    def handle_data(self, data):
        self.stack[-1].c.append(data)


def parse(html):
    p = Parser()
    p.feed(html)
    return p.root


