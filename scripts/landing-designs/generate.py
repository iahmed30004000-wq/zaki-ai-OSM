def shell_css(html):
    """The chrome every design shares, from one design's own sheet."""
    head = html[:html.find('<body')]
    shell = next(s for s in styles_in(head) if ':root' in s[:400])
    shell = strip_comments(shell)
    keep_heads = ['.' + RENAME.get(h, h) for h in ('lp-navbar', 'btn-brand', 'container', 'lp-footer', 'order-section')]
    css = rescope(shell, lambda s: any(re.match(re.escape(h) + r'(?![\w-])', s) for h in keep_heads))
    # Their global reset (`*{margin:0;padding:0;font-family:…!important}`,
    # `body{…}`, `a{…}`, `img{…}`) is NOT carried over as written: on our page
    # it would reach our form and our blocks. `design-css.ts` re-states it,
    # scoped to their sections, at the weight it had on their page.
    return css


def wrap_module(js):
    # Their code, verbatim: our lint rules are not theirs to follow.
    return HEADER + '/* eslint-disable */\n// @ts-nocheck\n' + 'export function start() {\n' + js.strip() + '\n}\n'


def ts_str(s):
    return json.dumps(s, ensure_ascii=False)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


