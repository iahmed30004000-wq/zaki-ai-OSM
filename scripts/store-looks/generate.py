"""
THE STORE LOOKS AND HOME DESIGNS, GENERATED FROM THE HARVEST — the owner's
own platform's theme library and home designs, carried over literally where
they are a look, and mapped onto OUR blocks where they are a page.

    python -I scripts/store-looks/generate.py <yazeed-store-themes-harvest.json>

Reads, from the harvest of /web/settings/theme, /web/settings/theme-builder
and /web/home-builder/index:

  · `assets['/web/css/themes.css']` — every theme as `html[data-theme=<id>]`
    tokens (colours, radii, shadows). Their per-theme stylesheet IS those
    tokens; it is rescoped here onto our own variable names.
  · `window.themeLibraryBoot.themes` — the 13 themes' Arabic label, line and
    light/dark mode, as the library shows them.
  · `window.BUILDER_CONFIG.homeTemplates` — the 18 home designs: which theme
    each wears, and its sections as widgets.

and writes, under `src/lib/store-looks/`:

  · `ids.generated.ts`      the two id lists, alone: the theme schema reads them, and
                            a schema must not pull every token into every bundle.
  · `tokens.generated.ts`   the 13 looks' tokens. No Arabic, no photograph.
  · `designs.generated.ts`  the 18 designs as OUR block plans (block types and
                            their shape — sort, limit, size), plus the list of
                            their widgets that have no honest block here. No
                            Arabic: a plan has no field that could carry a
                            sentence of theirs.
  · `names.generated.ts`    the Arabic names the SELLER's gallery shows (each
                            theme's label and line, each design's name). The
                            one file that may hold Arabic, and it reaches no
                            shopper.

WHAT IS NEVER COPIED: their copy (slide titles, marquee phrases, banner
promises, «توصيل سريع», countdown dates), their photographs, their category
ids and their product ids. A widget whose only content is their words or
their data is LEFT OUT and named in the plan's `left` list.

Re-runnable: same harvest in, same files out. The harvest is data — this
script only parses it; nothing in it is executed.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'src', 'lib', 'store-looks')

HEADER = (
    '// GENERATED by scripts/store-looks/generate.py from the harvest of the owner\'s own\n'
    '// platform — do not edit by hand; change the generator and run it again.\n'
)

# ─────────────────────────────────────────────────────────────────────────
# Reading the boot objects out of a page
# ─────────────────────────────────────────────────────────────────────────


def grab(html, name):
    """The `window.<name> = {...}` literal, as text (JSON in every page read here)."""
    i = html.find('window.' + name)
    if i < 0:
        raise SystemExit('missing window.' + name)
    j = html.index('=', i) + 1
    while html[j].isspace():
        j += 1
    opener = html[j]
    closer = '}' if opener == '{' else ']'
    depth, quote, esc = 0, None, False
    for k in range(j, len(html)):
        c = html[k]
        if quote:
            if esc:
                esc = False
            elif c == '\\':
                esc = True
            elif c == quote:
                quote = None
            continue
        if c in '"\'`':
            quote = c
            continue
        if c == opener:
            depth += 1
        elif c == closer:
            depth -= 1
            if depth == 0:
                return json.loads(html[j:k + 1])
    raise SystemExit('unterminated window.' + name)


# ─────────────────────────────────────────────────────────────────────────
# themes.css → tokens
# ─────────────────────────────────────────────────────────────────────────

TOKEN_RE = re.compile(r'--theme-([a-z0-9-]+)\s*:\s*([^;]+);')


def theme_blocks(css):
    """{theme id: {token: value}} — `:root, html[data-theme="light"]` is the base every theme inherits."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    out = {}
    for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', css):
        head, body = m.group(1), m.group(2)
        ids = re.findall(r'html\[data-theme="([a-z]+)"\]\s*$', head.strip()) or re.findall(
            r'html\[data-theme="([a-z]+)"\](?=\s*(?:,|$))', head
        )
        is_root = head.strip().startswith(':root')
        tokens = {t: v.strip() for t, v in TOKEN_RE.findall(body)}
        if not tokens:
            continue
        keys = (['__root__'] if is_root else []) + ids
        for key in keys:
            out.setdefault(key, {}).update(tokens)
    return out


def resolve(tokens, value, depth=0):
    """`var(--theme-radius-sm)` → that token's own value."""
    m = re.fullmatch(r'var\(--theme-([a-z0-9-]+)\)', value.strip())
    if not m or depth > 4:
        return value
    return resolve(tokens, tokens.get(m.group(1), value), depth + 1)


HEX = re.compile(r'^#[0-9a-fA-F]{6}$')
LEN = re.compile(r'^(0|\d{1,3}px)$')
SHADOW = re.compile(r'^[0-9a-z.,()# %-]+$')


def look_of(theme_id, root, own, mode):
    tokens = {**root, **own}
    get = lambda name: resolve(tokens, tokens[name])
    colours = {
        'background': 'color-bg', 'surface': 'color-surface', 'raised': 'color-surface-raised',
        'primary': 'color-primary', 'primarySoft': 'color-primary-soft', 'secondary': 'color-secondary',
        'text': 'color-text', 'muted': 'color-text-muted', 'inverse': 'color-text-inverse',
        'border': 'color-border', 'success': 'color-success', 'warning': 'color-warning', 'danger': 'color-danger',
    }
    colors = {k: get(v).lower() for k, v in colours.items()}
    for k, v in colors.items():
        if not HEX.match(v):
            raise SystemExit(f'{theme_id}.{k}: not a colour: {v}')
    navbar = get('navbar-bg').lower()
    if not HEX.match(navbar):
        navbar = colors['raised']
    radius = {
        'sm': get('radius-sm'), 'md': get('radius-md'), 'lg': get('radius-lg'),
        'button': get('button-radius'), 'card': get('card-radius'), 'field': get('form-radius'),
    }
    for k, v in radius.items():
        if not LEN.match(v):
            raise SystemExit(f'{theme_id}.radius.{k}: not a length: {v}')
        radius[k] = '0px' if v == '0' else v
    shadow = {k: get('shadow-' + k) for k in ('sm', 'md', 'lg')}
    for k, v in shadow.items():
        # `var(--theme-color-border)` inside a shadow is rescoped onto ours.
        v = v.replace('var(--theme-color-border)', 'var(--store-border)')
        if v != 'none' and not SHADOW.match(v.replace('var(--store-border)', '')):
            raise SystemExit(f'{theme_id}.shadow.{k}: unexpected: {v}')
        shadow[k] = v
    return {'id': theme_id, 'mode': mode, 'colors': colors, 'navbar': navbar, 'radius': radius, 'shadow': shadow}


# ─────────────────────────────────────────────────────────────────────────
# A home design → our blocks
# ─────────────────────────────────────────────────────────────────────────

SORT = {'best_sellers': 'best', 'new_arrivals': 'newest', 'price_low': 'priceAsc'}


def widgets_of(template):
    for section in template['layout']['sections']:
        for row in section['rows']:
            for col in row['columns']:
                for w in col['widgets']:
                    yield w


def plan_of(template):
    """
    Their widgets, in order, as our block plans. Rules, each one a decision:

      hero (video · slider · «البانر والعروض»)      → `slider`, empty: the seller's own slides
      product rows (tabs · products · best/new)     → `catalog` of products, sorted the way theirs was
      featured product · spotlight                  → `catalog`, one product, large: the best seller
      categories (cards · circles · chips · tiles)  → the next product row shows the category chips
      trust row · features · reasons                → `trust`: the facts the server measured
      faq                                           → `faq`, no questions of theirs
      collage                                       → `gallery`, empty: the seller's own photographs

    Left out, and why — written into `left`:
      marquee      their phrases are their words; our header ticker carries the seller's own
      banners      promotion tiles whose words and links are theirs
      cta banner   the same: a sentence and a button of theirs
      whatsapp     every shop already has the floating WhatsApp button
      countdown    a date they invented — our countdown needs a real offer's ending
      heading/text/button/image  their copy and their photograph
      brands       no brand record exists here
      newsletter   no e-mail capture exists here, and a COD shop does not need one
      budget       no price-band block exists here yet
      category rows / a category's own row  their category ids mean nothing in another shop
      reviews      a shop home has no product, so the reviews block there would only
                   show what a seller typed — never a delivered order's rating. Feeding
                   it the store's verified ratings would change every home that already
                   holds one, so it waits (BACKLOG)
    """
    blocks, left = [], []
    wants_categories = False
    have_slider = have_trust = have_faq = False

    def products(sort, limit, columns=4, size='md'):
        nonlocal wants_categories
        block = {'type': 'catalog', 'source': 'products', 'sort': sort, 'limit': max(0, min(int(limit or 0), 24)),
                 'columns': columns, 'cardSize': size, 'showCategories': wants_categories}
        wants_categories = False
        blocks.append(block)

    for w in widgets_of(template):
        t, s = w['type'], w.get('settings') or {}
        named = s.get('section') if t == 'storeSection' else None
        if t in ('storeVideo', 'storeSlider') or named == 'hero':
            if not have_slider:
                blocks.append({'type': 'slider'})
                have_slider = True
        elif t in ('storeCategories', 'imagebox') or named == 'categories':
            wants_categories = True
        elif t == 'storeTabs':
            first = (s.get('tabs') or [{}])[0].get('source')
            products(SORT.get(first, 'shelf'), s.get('limit'))
        elif t == 'storeProducts':
            if s.get('source') == 'category':
                left.append('categoryRow')
            else:
                products(SORT.get(s.get('source'), 'shelf'), s.get('limit'))
        elif named in ('best_sellers', 'new_arrivals'):
            products(SORT[named], 10)
        elif t == 'storeFeatured' or named == 'spotlight':
            products('best', 1, columns=2, size='lg')
        elif t == 'storeReviews' or named == 'testimonials':
            left.append('reviews')
        elif t in ('storeTrust', 'features') or named in ('trust', 'reasons'):
            if not have_trust:
                blocks.append({'type': 'trust'})
                have_trust = True
        elif named == 'faq':
            if not have_faq:
                blocks.append({'type': 'faq'})
                have_faq = True
        elif t == 'storeMosaic':
            blocks.append({'type': 'gallery'})
        else:
            reason = {
                'storeMarquee': 'marquee', 'storeBanners': 'banners', 'ctabanner': 'ctaBanner',
                'storeWhatsapp': 'whatsapp', 'countdown': 'countdown', 'heading': 'copy', 'text': 'copy',
                'button': 'copy', 'image': 'copy',
            }.get(t) or {
                'brands': 'brands', 'newsletter': 'newsletter', 'budget': 'budget', 'category_rows': 'categoryRow',
            }.get(named)
            if not reason:
                raise SystemExit(f'{template["id"]}: a widget nobody decided about: {t} {named}')
            left.append(reason)
    if not have_slider:
        raise SystemExit(f'{template["id"]}: no first screen')
    return blocks, sorted(set(left))


# ─────────────────────────────────────────────────────────────────────────
# Their seller-facing lines, kept where they describe a LOOK
# ─────────────────────────────────────────────────────────────────────────

# Three of the thirteen lines go on to promise a part of THEIR storefront that
# a look here does not draw. The line is cut at that clause, never rewritten.
CUT_AT = {
    'souq': '، عدد المبيعات',
    'studio': '، عناوين أقسام',
    'atelier': '، واجهة فيديو',
}

# And four more name a part of their storefront mid-sentence. The words are
# taken out, never replaced (the review of #188, item 9): a quick «add»
# button on the card, motion as you scroll (a look sets no motion — that is
# «الحركة»), large banners, dense rows.
DROP = {
    'nova': [' مع إضافة سريعة'],
    'pulse': [' متحرك', ' وحركات لطيفة مع التمرير'],
    'voyage': ['بانرات كبيرة، '],
    'mega': ['صفوف كثيفة و'],
}


def ts(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    with open(sys.argv[1], encoding='utf-8') as f:
        harvest = json.load(f)
    pages, assets = harvest['pages'], harvest['assets']

    library = grab(pages['/web/settings/theme']['html'], 'themeLibraryBoot')
    builder = grab(pages['/web/home-builder/index']['html'], 'BUILDER_CONFIG')
    blocks = theme_blocks(assets['/web/css/themes.css'])
    root = blocks['__root__']

    theme_ids = list(library['themes'].keys())
    looks = []
    names = {'looks': {}, 'designs': {}}
    for tid in theme_ids:
        meta = library['themes'][tid]
        looks.append(look_of(tid, root, blocks.get(tid, {}), meta['mode']))
        line = meta['description']
        if tid in CUT_AT and CUT_AT[tid] in line:
            line = line.split(CUT_AT[tid])[0] + '.'
        for words in DROP.get(tid, []):
            if words not in line:
                raise SystemExit(f'{tid}: the words to drop are not in the line any more: {words}')
            line = line.replace(words, '')
        names['looks'][tid] = {'label': meta['label'], 'line': line}

    designs = []
    for t in builder['homeTemplates']:
        if t['theme'] not in theme_ids:
            raise SystemExit(f'{t["id"]}: wears a theme nobody harvested: {t["theme"]}')
        plan, left = plan_of(t)
        designs.append({'id': t['id'], 'look': t['theme'], 'blocks': plan, 'left': left})
        names['designs'][t['id']] = t['name']

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'ids.generated.ts'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER + '\n')
        f.write('export const LOOK_IDS = ' + json.dumps(theme_ids) + ' as const;\n\n')
        f.write('export const HOME_DESIGN_IDS = ' + json.dumps([d['id'] for d in designs]) + ' as const;\n')
    with open(os.path.join(OUT, 'tokens.generated.ts'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER + "import type { LookTokens } from './types';\n\n")
        f.write('export const LOOK_TOKENS: readonly LookTokens[] = ' + ts(looks) + ';\n')
    with open(os.path.join(OUT, 'designs.generated.ts'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER + "import type { HomeDesignPlan } from './types';\n\n")
        f.write('export const HOME_DESIGN_PLANS: readonly HomeDesignPlan[] = ' + ts(designs) + ';\n')
    with open(os.path.join(OUT, 'names.generated.ts'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER + '// The SELLER\'s gallery reads these; no shopper page imports this file.\n\n')
        f.write('export const LOOK_NAMES: Readonly<Record<string, { label: string; line: string }>> = '
                + ts(names['looks']) + ';\n\n')
        f.write('export const DESIGN_NAMES: Readonly<Record<string, string>> = ' + ts(names['designs']) + ';\n')
    print(f'{len(looks)} looks, {len(designs)} designs')


if __name__ == '__main__':
    main()
