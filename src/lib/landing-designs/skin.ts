/**
 * A DESIGN, AS OUR RENDERER WEARS IT — the shape `generated/<id>.ts` holds.
 *
 * The owner, 3/11: his other platform's sixty-four designs come over «بشكل
 * حرفي», and OUR parts stay ours — our blocks and their content, our order
 * form, our offers, our upsell, our pixels, our real reviews. So a design here
 * is a LOOK and nothing else:
 *
 *   · its stylesheet, rescoped under `[data-design]` so it styles nothing
 *     outside the page that wears it;
 *   · its colours and its typeface;
 *   · its sections as TEMPLATES — the exact elements, classes and inline
 *     styles their builder wrote, with every word taken out.
 *
 * A template has no field that could hold a sentence. That is the guarantee
 * that none of their default copy («+50K عميل سعيد», «ضمان استرداد 60 يوم»,
 * reviews nobody wrote) can reach a customer: the words on a designed page are
 * our blocks' words, filled in by `DesignedBlocks.tsx`, or they are nothing.
 *
 * Generated by `scripts/landing-designs/generate.py` from the harvest; the id
 * list and the lazy loaders are in `src/components/landing/designs/generated/index.ts`. The catalogue's
 * names, categories and swatches are `catalog.ts` (the library's), and this
 * file reads none of it: an id is the whole contract between the two.
 */

/** An inline style, already in React's casing (`--x` custom properties kept). */
export type DesignStyle = Record<string, string>;

interface WidgetBase {
  /** The widget's classes, motion hooks (`mx-up`, `bpr-anim`, `imx-stage`…) included. */
  cls: string;
  style?: DesignStyle;
}

/** Which of our words a heading takes. Decided by the generator from its tag and place. */
export type HeadingSlot = 'kicker' | 'headline' | 'title' | 'price';

export type DesignWidget =
  | (WidgetBase & { k: 'heading'; tag: 'h1' | 'h2' | 'h3' | 'h4' | 'h5' | 'h6'; hcls: string; hstyle: DesignStyle; slot: HeadingSlot })
  | (WidgetBase & { k: 'text'; tcls: string; tstyle: DesignStyle })
  | (WidgetBase & { k: 'button'; bcls: string; acls: string; astyle: DesignStyle })
  | (WidgetBase & { k: 'image'; istyle: DesignStyle })
  | (WidgetBase & { k: 'checklist'; ulStyle: DesignStyle; liStyle: DesignStyle; markStyle: DesignStyle; mark: string })
  | (WidgetBase & {
      k: 'features';
      gcls: string;
      gstyle: DesignStyle;
      item: DesignStyle;
      icon: DesignStyle;
      strong: DesignStyle;
      span: DesignStyle;
      /** A «كيف تطلب» grid: its icons are step numbers, not pictures. */
      numbered: boolean;
      /** The pictures in their order, one per position. */
      icons: string[];
    })
  | (WidgetBase & { k: 'faq'; item: DesignStyle; button: DesignStyle; plus: DesignStyle; plusText: string; answer: DesignStyle })
  | (WidgetBase & {
      k: 'cta';
      boxCls: string;
      box: DesignStyle;
      /** Their banner sat on their product's photo; ours sits on our product's picture. */
      photo?: boolean;
      overlay: DesignStyle;
      inner: DesignStyle;
      h: DesignStyle;
      htag: string;
      p: DesignStyle;
      a: DesignStyle;
    })
  | (WidgetBase & { k: 'html'; parts: DesignHtmlPart[] });

/** A decorative element — an effect layer, a canvas, an svg. It carries no words. */
export interface DecoNode {
  t: string;
  a?: Record<string, string | DesignStyle>;
  c?: DecoNode[];
}

export type DesignHtmlPart =
  | { m: 'deco'; node: DecoNode }
  | { m: 'marquee'; cls: string; style: DesignStyle; sep: string }
  | { m: 'topbar'; cls: string; style: DesignStyle }
  /**
   * A kit section that carried their words. Its shape is the kit stylesheet's;
   * `DesignedBlocks.tsx` redraws the kinds that have a block of ours to fill
   * them (`cascade`, `road`, `facts`) and draws nothing for the others.
   */
  | { m: 'kit'; kind: string; cls: string; style: DesignStyle };

export interface DesignColumn {
  cls: string;
  widgets: DesignWidget[];
}

export interface DesignRow {
  cls: string;
  cols: DesignColumn[];
}

/**
 * What a section of theirs is FOR, read from what is in it.
 *
 * `hero` holds the h1; `trust` is a grid with no heading; `features` a grid
 * under a heading; `steps` a numbered grid; `why` a checklist; `zig` a
 * heading-and-photo row; `statement` a heading and a paragraph; `topbanner`
 * a banner above the hero; `cta` the banner before the order section.
 */
export type DesignRole =
  | 'announce'
  | 'topbanner'
  | 'hero'
  | 'image'
  | 'trust'
  | 'features'
  | 'steps'
  | 'why'
  | 'zig'
  | 'statement'
  | 'faq'
  | 'cta'
  | 'marquee'
  | 'topbar'
  | 'kit'
  | 'other';

export interface DesignSection {
  role: DesignRole;
  cls: string;
  container: DesignStyle | null;
  rows: DesignRow[];
}

export interface DesignSkin {
  id: string;
  /** One of the twenty-eight «imx-» designs, with a motion layer. */
  animated: boolean;
  /** Its widgets fade in on scroll (`bpr-anim`) — a few hundred bytes of script. */
  reveal: boolean;
  font: { family: string; google: string | null };
  vars: { primary: string; btn: string; orderHeader: string; ink: string; pageBg: string };
  /** The order section's own backdrop on a dark design, or null for theirs by default. */
  orderBg: string | null;
  /** Rescoped under `[data-design]`. */
  css: string;
  sections: DesignSection[];
}
