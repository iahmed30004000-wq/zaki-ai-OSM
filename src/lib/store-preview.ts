import { cookies, draftMode, headers } from 'next/headers';
import { db } from './db';
import { requireContext } from './geo-context';
import { requirePermission } from './authorization';

/**
 * «المعاينة الحقيقية» — THE REAL SHOP, DRAWN FROM THE DRAFT, FOR ITS OWN STAFF ONLY.
 *
 * Their theme builder previews the actual storefront in a frame over six
 * pages before anything is published. Ours drew a miniature. This is the
 * other half: the same `/s/<store>/…` pages a customer opens, rendering the
 * DRAFT theme and the DRAFT home page — with every one of these true before
 * a single draft byte is read:
 *
 *   1. Next's draft mode is on — a cookie only `POST /api/store/preview` sets,
 *      after it checked the session and the permission (`storefront.view`),
 *      and whose value is regenerated by every build, so it cannot be guessed;
 *   2. the request is a FRAME (`Sec-Fetch-Dest: iframe`): the seller who
 *      previewed and then opens the shop in a tab sees what a customer sees,
 *      never the draft;
 *   3. the request carries a session, inside a company, with `storefront.view`
 *      — the same door the entry asked;
 *   4. the shop at this address is the store that session stands in, in that
 *      company — another company's draft is never one cookie away;
 *   5. and the preview cookie names that same store.
 *
 * Any doubt is «no preview»: the page is the live shop, exactly as any
 * visitor gets it. This function never throws.
 */
export const PREVIEW_COOKIE = 'zaki-store-preview';

export async function previewStoreIdFor(slug: string): Promise<string | null> {
  try {
    if (!(await draftMode()).isEnabled) return null;
    if ((await headers()).get('sec-fetch-dest') !== 'iframe') return null;
    const named = (await cookies()).get(PREVIEW_COOKIE)?.value;
    if (!named) return null;
    const ctx = await requireContext();
    await requirePermission('storefront.view');
    if (ctx.storeId !== named) return null;
    const store = await db.store.findFirst({
      where: { id: ctx.storeId, companyId: ctx.companyId, slug },
      select: { id: true },
    });
    return store?.id ?? null;
  } catch {
    return null;
  }
}

/** The six pages their builder previews, by our addresses. */
export const PREVIEW_PAGES = ['home', 'products', 'category', 'product', 'search', 'cart'] as const;
export type PreviewPage = (typeof PREVIEW_PAGES)[number];
